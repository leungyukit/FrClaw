fn build_js() -> &'static str {
    r#"
// 简单交互：点击 card 复制其内容到剪贴板
document.querySelectorAll('.card').forEach(c => {
  c.addEventListener('click', () => {
    const txt = c.querySelector('.content').innerText;
    navigator.clipboard.writeText(txt).then(() => {
      c.style.outline = '2px solid #4caf50';
      setTimeout(() => { c.style.outline = ''; }, 600);
    });
  });
  c.style.cursor = 'pointer';
  c.title = '点击复制内容';
});
"#
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn render_simple_session() {
        let messages = vec![
            json!({ "role": "user", "content": "hi" }),
            json!({ "role": "assistant", "content": "**hello**" }),
        ];
        let dir = std::env::temp_dir().join(format!("fr-timeline-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&dir).unwrap();
        let out = dir.join("timeline.html");
        let opts = TimelineOptions::default();
        render_messages(&messages, &opts, &out).unwrap();
        let s = std::fs::read_to_string(&out).unwrap();
        assert!(s.contains("<!DOCTYPE html>"));
        assert!(s.contains(">hi<"));
        assert!(s.contains(">hello<"));
        assert!(s.contains("timeline::before"));
    }

    #[test]
    fn render_session_json_path() {
        let session = serde_json::json!({
            "name": "test",
            "messages": [
                { "role": "user", "content": "Q1" },
                { "role": "assistant", "content": "A1" },
                { "role": "user", "content": "Q2" },
                { "role": "assistant", "content": "A2" },
            ]
        });
        let dir = std::env::temp_dir().join(format!("fr-timeline-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(&dir).unwrap();
        let out = dir.join("timeline.html");
        let opts = TimelineOptions::default();
        render_session_json(&session.to_string(), &opts, &out).unwrap();
        let s = std::fs::read_to_string(&out).unwrap();
        assert!(s.contains("4 messages"));
    }
}
